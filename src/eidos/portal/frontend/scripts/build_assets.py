#!/usr/bin/env python3
"""Regenerate the portal ``assets.py`` module from the Vite single-file build.

Usage (from the portal ``frontend`` directory)::

    pnpm install --frozen-lockfile
    pnpm build:assets          # == vite build && python3 scripts/build_assets.py

``assets.py`` embeds the single-file bundle (``dist/index.html``) as ``PORTAL_HTML_TEMPLATE`` and the
brand mark (``public/favicon.svg``) as ``PORTAL_FAVICON_SVG`` so that ``eidos portal serve`` and
``eidos portal build`` work from a plain ``pip install`` with no Node.js runtime (INV-PORTAL-ZERO-NODE-DEP).

The script refuses to emit a bundle that would violate INV-PORTAL-AIR-GAPPED-BUNDLE (remote
subresources) or the 5 MiB size budget; the same checks are enforced by ``tests/test_portal.py``.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

FRONTEND_DIR = Path(__file__).resolve().parent.parent
DEFAULT_ASSETS = FRONTEND_DIR.parent / "assets.py"
SIZE_BUDGET_BYTES = 5 * 1024 * 1024
HEADER = (
    "# Generated by build process. Do not edit directly.\n"
    "# Singlefile distribution of the Eidos Living Web Portal.\n"
    "# Regenerate with: pnpm build:assets (in the portal frontend directory; see scripts/build_assets.py)\n"
    "# ruff: noqa: RUF001  (bundled third-party JS legitimately contains non-ASCII characters)\n"
)

# Remote URL in a src=/href= attribute, an @import rule, or a CSS url(...) reference.
REMOTE_REF_RE = re.compile(
    r"""(?:\b(?:src|href)\s*=\s*["']?\s*(?:https?:)?//[^\s"'>]+)"""
    r"""|(?:@import\s+(?:url\(\s*)?["']?\s*(?:https?:)?//[^\s"')]+)"""
    r"""|(?:url\(\s*["']?\s*(?:https?:)?//[^\s"')]+)""",
    re.IGNORECASE,
)


def build_assets_source(html: str, favicon: str) -> str:
    return f"{HEADER}\nPORTAL_FAVICON_SVG = {favicon!r}\n\nPORTAL_HTML_TEMPLATE = {html!r}\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dist", type=Path, default=FRONTEND_DIR / "dist" / "index.html")
    parser.add_argument("--favicon", type=Path, default=FRONTEND_DIR / "public" / "favicon.svg")
    parser.add_argument("--out", type=Path, default=DEFAULT_ASSETS)
    args = parser.parse_args(argv)

    if not args.dist.is_file():
        print(f"error: {args.dist} not found - run 'vite build' first", file=sys.stderr)
        return 1

    html = args.dist.read_text(encoding="utf-8")
    favicon = args.favicon.read_text(encoding="utf-8")

    remote = REMOTE_REF_RE.findall(html)
    if remote:
        print("error: bundle references remote subresources:", file=sys.stderr)
        for ref in remote[:10]:
            print(f"  {ref}", file=sys.stderr)
        return 1
    if "<script" not in html or '<div id="root"></div>' not in html:
        print("error: bundle does not look like the single-file portal build", file=sys.stderr)
        return 1
    if html.count("</head>") != 1:
        print(
            "error: bundle must contain exactly one '</head>' (builder.py injects data before the first one)",
            file=sys.stderr,
        )
        return 1
    size = len(html.encode("utf-8"))
    if size > SIZE_BUDGET_BYTES:
        print(f"error: bundle is {size} bytes, over the {SIZE_BUDGET_BYTES} byte budget", file=sys.stderr)
        return 1

    args.out.write_text(build_assets_source(html, favicon), encoding="utf-8")
    print(f"wrote {args.out} ({size / 1024 / 1024:.2f} MiB bundle)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
