#!/usr/bin/env python3
"""Emit and verify the portal single-file bundle assets from the Vite single-file build.

Usage (from the portal ``frontend`` directory)::

    pnpm install --frozen-lockfile
    pnpm build:assets          # == vite build && python3 scripts/build_assets.py
    python3 scripts/build_assets.py --check   # verify bundle parity in CI

By default, ``build_assets.py`` writes deterministic gzip-compressed ``assets/portal/bundle.html.gz``
and ``assets/portal/favicon.svg`` (and also supports ``--out <path.py>`` to emit a Python literal module)
so that ``eidos portal serve`` and ``eidos portal build`` work from a plain ``pip install`` with no
Node.js runtime (INV-PORTAL-ZERO-NODE-DEP) without committing a 4.7 MB single-line Python string literal.

The script refuses to emit or pass a bundle that would violate INV-PORTAL-AIR-GAPPED-BUNDLE (remote
subresources) or the 5 MiB uncompressed size budget; the same checks are enforced by ``tests/test_portal.py``.
"""

from __future__ import annotations

import argparse
import gzip
import re
import sys
from pathlib import Path

FRONTEND_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = FRONTEND_DIR.parents[3]
DEFAULT_PORTAL_ASSETS_DIR = REPO_ROOT / "assets" / "portal"
SIZE_BUDGET_BYTES = 5 * 1024 * 1024
HEADER = (
    "# Generated by build process. Do not edit directly.\n"
    "# Singlefile distribution of the Eidos Living Web Portal.\n"
    "# Regenerate with: pnpm build:assets (in the portal frontend directory; see scripts/build_assets.py)\n"
    "# ruff: noqa: RUF001  (bundled third-party JS legitimately contains non-ASCII characters)\n"
)

# Remote URL in a src=/href= attribute, an @import rule, or a CSS url(...) reference.
REMOTE_REF_RE = re.compile(
    r"""(?:\b(?:src|href)\s*=\s*["']?\s*(?:https?:)?//[^\s"'>]+)"""
    r"""|(?:@import\s+(?:url\(\s*)?["']?\s*(?:https?:)?//[^\s"')]+)"""
    r"""|(?:url\(\s*["']?\s*(?:https?:)?//[^\s"')]+)""",
    re.IGNORECASE,
)


def build_assets_source(html: str, favicon: str) -> str:
    return f"{HEADER}\nPORTAL_FAVICON_SVG = {favicon!r}\n\nPORTAL_HTML_TEMPLATE = {html!r}\n"


def compress_bundle_deterministic(html: str) -> bytes:
    """Compress the HTML bundle with deterministic gzip headers (mtime=0, level=9)."""
    return gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)


def validate_bundle(html: str) -> list[str]:
    """Validate air-gapped single-file invariants and size budget on the HTML bundle."""
    errors: list[str] = []
    remote = REMOTE_REF_RE.findall(html)
    if remote:
        errors.append(f"bundle references remote subresources: {', '.join(remote[:5])}")
    if "<script" not in html or '<div id="root"></div>' not in html:
        errors.append("bundle does not look like the single-file portal build")
    if html.count("</head>") != 1:
        errors.append("bundle must contain exactly one '</head>' (builder.py injects data before the first one)")
    size = len(html.encode("utf-8"))
    if size > SIZE_BUDGET_BYTES:
        errors.append(f"bundle is {size} bytes, over the {SIZE_BUDGET_BYTES} byte budget")
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dist", type=Path, default=FRONTEND_DIR / "dist" / "index.html")
    parser.add_argument("--favicon", type=Path, default=FRONTEND_DIR / "public" / "favicon.svg")
    parser.add_argument(
        "--assets-dir",
        type=Path,
        default=DEFAULT_PORTAL_ASSETS_DIR,
        help="Target directory for bundle.html.gz and favicon.svg (default: assets/portal)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="Optional path to emit a standalone Python assets module (or target assets directory).",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify that the packaged portal bundle matches dist/index.html and public/favicon.svg without modifying files.",
    )
    args = parser.parse_args(argv)

    if not args.dist.is_file():
        print(f"error: {args.dist} not found - run 'vite build' first", file=sys.stderr)
        return 1

    html = args.dist.read_text(encoding="utf-8")
    favicon = args.favicon.read_text(encoding="utf-8")

    errors = validate_bundle(html)
    if errors:
        for err in errors:
            print(f"error: {err}", file=sys.stderr)
        return 1

    size = len(html.encode("utf-8"))

    if args.out is not None and args.out.suffix == ".py":
        expected_source = build_assets_source(html, favicon)
        if args.check:
            if not args.out.is_file() or args.out.read_text(encoding="utf-8") != expected_source:
                print(
                    f"error: {args.out} is out of date with {args.dist} - run 'pnpm build:assets'",
                    file=sys.stderr,
                )
                return 1
            print(f"verified {args.out} matches {args.dist}")
            return 0
        args.out.write_text(expected_source, encoding="utf-8")
        print(f"wrote {args.out} ({size / 1024 / 1024:.2f} MiB bundle)")
        return 0

    target_dir = args.out if args.out is not None else args.assets_dir
    bundle_gz_path = target_dir / "bundle.html.gz"
    favicon_out_path = target_dir / "favicon.svg"

    if args.check:
        if not bundle_gz_path.is_file() or not favicon_out_path.is_file():
            print(
                f"error: portal assets missing in {target_dir} - run 'pnpm build:assets'",
                file=sys.stderr,
            )
            return 1
        actual_html = gzip.decompress(bundle_gz_path.read_bytes()).decode("utf-8")
        actual_favicon = favicon_out_path.read_text(encoding="utf-8")
        if actual_html != html or actual_favicon != favicon:
            print(
                f"error: {bundle_gz_path} is out of sync with {args.dist} - run 'pnpm build:assets'",
                file=sys.stderr,
            )
            return 1
        print(f"verified {bundle_gz_path} matches {args.dist} ({size / 1024 / 1024:.2f} MiB uncompressed)")
        return 0

    target_dir.mkdir(parents=True, exist_ok=True)
    compressed = compress_bundle_deterministic(html)
    bundle_gz_path.write_bytes(compressed)
    favicon_out_path.write_text(favicon, encoding="utf-8")
    print(f"wrote {bundle_gz_path} ({len(compressed) / 1024 / 1024:.2f} MiB gzip / {size / 1024 / 1024:.2f} MiB raw)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
